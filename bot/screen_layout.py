# Границы зоны, куда игра РАЗРЕШАЕТ ставить карты (своя половина)
MIN_DEPLOY_Y = 0.455
MAX_DEPLOY_Y = 0.800
MIN_DEPLOY_X = 0.06
MAX_DEPLOY_X = 0.94


def hand_slot_box(slot: int, w: int, h: int) -> Tuple[int, int, int, int]:
    """Прямоугольник слота руки (x1, y1, x2, y2) на экране w x h."""
    slot = max(0, min(3, slot))
    cx = HAND_SLOT_X[slot] * w
    cy = HAND_SLOT_Y * h
    hw = HAND_HALF_W * w
    hh = HAND_HALF_H * h
    return (int(cx - hw), int(cy - hh), int(cx + hw), int(cy + hh))


def hand_slot_tap(slot: int, w: int, h: int) -> Tuple[int, int]:
    """Точка клика по слоту руки."""
    slot = max(0, min(3, slot))
    return int(HAND_SLOT_X[slot] * w), int(HAND_SLOT_Y * h)


def arena_point(name: str, w: int, h: int) -> Tuple[int, int]:
    """Точка установки карты на арене.
    Координаты прижимаются к разрешённой зоне — иначе игра не даст поставить карту."""
    x, y = ARENA_POINTS.get(name, ARENA_POINTS["center"])
    x = min(MAX_DEPLOY_X, max(MIN_DEPLOY_X, x))
    y = min(MAX_DEPLOY_Y, max(MIN_DEPLOY_Y, y))
    return int(w * x), int(h * y)
