                    this.rightArm.yRot = -0.32F * env;
                    this.rightForearm.xRot = -1.35F * env;
                    this.rightHand.xRot = 0.92F * env;
                    this.leftArm.xRot = -0.95F * env;
                    this.leftArm.yRot = 0.32F * env;
                    this.leftForearm.xRot = -1.35F * env;
                    this.leftHand.xRot = 0.92F * env;
                    this.rightLeg.xRot = -0.18F * env; this.rightShin.xRot = 0.30F * env;
