                    this.rightLeg.yRot = -0.16F * env; this.rightShin.xRot = 0.12F * env;
                    this.leftLeg.yRot = 0.16F * env; this.leftShin.xRot = 0.12F * env;
                    setWings(0.24F + 0.08F * pulse, -0.12F);
