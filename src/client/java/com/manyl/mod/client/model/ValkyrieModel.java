                    float barkOpen = Math.max(b1, b2);
                    this.blush.visible = true;
                    this.mouthClosed.visible = barkOpen <= 0.15F;
                    this.mouthOpen.visible = barkOpen > 0.15F;
                    this.mouthOpen.yScale = 0.45F + 0.95F * barkOpen;
