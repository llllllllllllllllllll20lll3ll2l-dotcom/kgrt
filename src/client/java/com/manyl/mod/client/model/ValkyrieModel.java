    private void setWings(float open, float sweep) {
        this.wingRightInner.yRot = open;
        this.wingLeftInner.yRot = -open;
        this.wingRightInner.zRot = -sweep;
        this.wingLeftInner.zRot = sweep;
        this.wingRightOuter.yRot = open * 0.60F;
        this.wingLeftOuter.yRot = -open * 0.60F;
        this.wingRightOuter.zRot = -sweep * 0.70F;
        this.wingLeftOuter.zRot = sweep * 0.70F;
    }

    private static void setPartScaleAndFade(ModelPart part, float progress) {
        if (progress <= 0.0F) {
            part.visible = true;
            part.xScale = 1.0F;
            part.yScale = 1.0F;
            part.zScale = 1.0F;
            return;
        }
        if (progress >= 0.95F) {
            part.visible = false;
            return;
        }
        part.visible = true;
        float sc = Math.max(0.02F, 1.0F - progress);
        part.xScale = sc;
        part.yScale = sc;
        part.zScale = sc;
        part.y -= 36.0F * progress;
    }

    private static float smooth01(float x) {
        float t = Mth.clamp(x, 0.0F, 1.0F);
        return t * t * (3.0F - 2.0F * t);
    }

    private static float bell(float t, float start, float peakIn, float peakOut, float end) {
        if (t <= start || t >= end) return 0.0F;
        if (t < peakIn) return smooth01((t - start) / Math.max(0.001F, peakIn - start));
        if (t > peakOut) return 1.0F - smooth01((t - peakOut) / Math.max(0.001F, end - peakOut));
        return 1.0F;
    }

